    private static java.util.Map<String, String> cols(String... paresNombreTipo) {
        java.util.Map<String, String> m = new java.util.LinkedHashMap<>();
        for (int i = 0; i < paresNombreTipo.length; i += 2) m.put(paresNombreTipo[i], paresNombreTipo[i + 1]);
        return m;
    }

    /**
     * Migración automática: CREATE TABLE IF NOT EXISTS no modifica tablas que ya existen, así que una base
     * creada con otra versión del sistema puede traer columnas distintas. Aquí:
     *  - se agregan las columnas que faltan;
     *  - las columnas "extra" obligatorias (NOT NULL) se vuelven opcionales, para que los INSERT de esta
     *    versión no fallen (ej.: "NULL not allowed for column ID_PERFIL").
     * No se borra ninguna columna ni ningún dato.
     */
    private static void adaptarEsquemaAntiguo(Statement st) throws SQLException {
        for (var tabla : ESQUEMA.entrySet()) {
            java.util.Map<String, Boolean> existentes = new java.util.LinkedHashMap<>(); // columna -> admite NULL
            try (PreparedStatement ps = getConnection().prepareStatement(
                    "SELECT COLUMN_NAME, IS_NULLABLE FROM INFORMATION_SCHEMA.COLUMNS " +
                    "WHERE TABLE_SCHEMA='PUBLIC' AND TABLE_NAME=?")) {
                ps.setString(1, tabla.getKey());
                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) existentes.put(rs.getString(1).toUpperCase(), "YES".equalsIgnoreCase(rs.getString(2)));
                }
            }
            for (var col : tabla.getValue().entrySet()) {
                if (!existentes.containsKey(col.getKey())) {
                    try {
                        st.execute("ALTER TABLE " + tabla.getKey() + " ADD COLUMN " + col.getKey() + " " + col.getValue());
                    } catch (SQLException ignorado) { /* se reporta al usar la tabla */ }
                }
            }
            repararColumnaId(st, tabla.getKey(), tabla.getValue().keySet().iterator().next());
            ampliarColumnasTexto(st, tabla.getKey(), tabla.getValue());
            for (var existente : existentes.entrySet()) {
                boolean esExtra = !tabla.getValue().containsKey(existente.getKey());
                if (esExtra && !existente.getValue()) {
                    try {
                        st.execute("ALTER TABLE " + tabla.getKey() + " ALTER COLUMN " + existente.getKey() + " DROP NOT NULL");
                    } catch (SQLException ignorado) { /* columna que no admite el cambio */ }
                }
            }
        }
    }

    /**
     * Bases creadas con versiones anteriores pueden tener columnas de texto más cortas de lo que usa esta
     * versión (por ejemplo boleta.numero VARCHAR(8) y el número "BOL-20261124-1" tiene 14 caracteres).
     * Solo se AMPLÍAN (nunca se reducen), así que no se pierde ni se corta ningún dato.
     */
    private static void ampliarColumnasTexto(Statement st, String tabla, java.util.Map<String, String> columnas) {
        for (var col : columnas.entrySet()) {
            String tipo = col.getValue().toUpperCase();
            if (!tipo.startsWith("VARCHAR(")) continue;
            int deseado = Integer.parseInt(tipo.substring(8, tipo.length() - 1));
            try (PreparedStatement ps = getConnection().prepareStatement(
                    "SELECT CHARACTER_MAXIMUM_LENGTH FROM INFORMATION_SCHEMA.COLUMNS " +
                    "WHERE TABLE_SCHEMA='PUBLIC' AND TABLE_NAME=? AND COLUMN_NAME=?")) {
                ps.setString(1, tabla);
                ps.setString(2, col.getKey());
                try (ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) continue;
                    long actual = rs.getLong(1);
                    if (actual >= deseado) continue;
                }
                st.execute("ALTER TABLE " + tabla + " ALTER COLUMN " + col.getKey() + " SET DATA TYPE " + col.getValue());
            } catch (SQLException e) {
                System.err.println("No se pudo ampliar " + tabla + "." + col.getKey() + ": " + e.getMessage());
            }
        }
    }

    /**
     * Si la columna ID de la tabla existe pero no se autogenera (caso de una base creada con una versión
     * anterior, donde la migración agregó ID_CLIENTE, ID_DESTINO, etc. como columna vacía), se le asigna
     * un número a cada fila existente y se deja con valor automático para los registros nuevos.
     */
    private static void repararColumnaId(Statement st, String tabla, String id) {
        try {
            boolean autogenerada = false;
            try (PreparedStatement ps = getConnection().prepareStatement(
                    "SELECT IS_IDENTITY, COLUMN_DEFAULT FROM INFORMATION_SCHEMA.COLUMNS " +
                    "WHERE TABLE_SCHEMA='PUBLIC' AND TABLE_NAME=? AND COLUMN_NAME=?")) {
                ps.setString(1, tabla);
                ps.setString(2, id);
                try (ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) return;
                    autogenerada = "YES".equalsIgnoreCase(rs.getString(1)) || rs.getString(2) != null;
                }
            }
            if (autogenerada) return;
            long inicio;
            try (ResultSet rs = st.executeQuery("SELECT COALESCE(MAX(" + id + "),0)+1 FROM " + tabla)) {
                rs.next();
                inicio = rs.getLong(1);
            }
            String seq = "SEQ_" + tabla;
            st.execute("CREATE SEQUENCE IF NOT EXISTS " + seq + " START WITH " + inicio);
            st.execute("UPDATE " + tabla + " SET " + id + " = NEXT VALUE FOR " + seq + " WHERE " + id + " IS NULL");
            st.execute("ALTER TABLE " + tabla + " ALTER COLUMN " + id + " SET DEFAULT NEXT VALUE FOR " + seq);
        } catch (SQLException e) {
            System.err.println("No se pudo reparar la columna " + id + " de " + tabla + ": " + e.getMessage());
        }
    }

