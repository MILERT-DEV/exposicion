    /**
     * Carpeta donde viven la base de datos y los comprobantes.
     * - Si existe ./data junto al proyecto (modo desarrollo), se usa esa.
     * - Si no, se usa ~/SysTurismo/data, que siempre tiene permiso de escritura
     *   (importante para el .exe instalado en Program Files).
     * - Se puede forzar con -Dsysturismo.data=RUTA.
     */
    public static Path carpetaDatos() {
        if (carpetaDatos == null) {
            String forzada = System.getProperty("systurismo.data");
            if (forzada != null && !forzada.isBlank()) carpetaDatos = Path.of(forzada);
            else if (Files.isDirectory(Path.of("data"))) carpetaDatos = Path.of("data");
            else carpetaDatos = Path.of(System.getProperty("user.home"), "SysTurismo", "data");
            carpetaDatos = carpetaDatos.toAbsolutePath();
        }
        return carpetaDatos;
    }

    private static String url() {
        return "jdbc:h2:file:" + carpetaDatos().resolve("systurismo").toString().replace('\\', '/') + ";AUTO_SERVER=TRUE";
    }

    public static Connection getConnection() throws SQLException {
        if (conexion == null || conexion.isClosed()) {
            conexion = DriverManager.getConnection(url(), "sa", "");
        }
        return conexion;
    }

