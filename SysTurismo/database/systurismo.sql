-- Base de datos SysTurismo para H2.
-- La aplicación ejecuta estas instrucciones al iniciar por primera vez.
CREATE TABLE usuario (
  id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario VARCHAR(30) UNIQUE NOT NULL,
  clave VARCHAR(200) NOT NULL,
  rol VARCHAR(20) NOT NULL
);
CREATE TABLE cliente (
  id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni VARCHAR(8) UNIQUE NOT NULL,
  nombres VARCHAR(100) NOT NULL,
  correo VARCHAR(100),
  telefono VARCHAR(15)
);
CREATE TABLE destino (
  id_destino BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  ciudad VARCHAR(80) NOT NULL,
  descripcion VARCHAR(250)
);
CREATE TABLE paquete (
  id_paquete BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  id_destino BIGINT NOT NULL REFERENCES destino(id_destino),
  dias INT NOT NULL,
  precio DOUBLE NOT NULL,
  cupos INT NOT NULL
);
CREATE TABLE reserva (
  id_reserva BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente BIGINT NOT NULL REFERENCES cliente(id_cliente),
  id_paquete BIGINT NOT NULL REFERENCES paquete(id_paquete),
  fecha_reserva DATE NOT NULL,
  pasajeros INT NOT NULL,
  total DOUBLE NOT NULL,
  estado VARCHAR(20) NOT NULL
);
CREATE TABLE pago (
  id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva BIGINT NOT NULL REFERENCES reserva(id_reserva),
  fecha_pago DATE NOT NULL,
  monto DOUBLE NOT NULL,
  metodo VARCHAR(30) NOT NULL,
  estado VARCHAR(20) NOT NULL
);
CREATE TABLE boleta (
  id_boleta BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva BIGINT NOT NULL REFERENCES reserva(id_reserva),
  fecha_emision DATE NOT NULL,
  numero VARCHAR(40) UNIQUE NOT NULL,
  total DOUBLE NOT NULL
);
